        public const string GeneratedNamespace = "ThreeSouls.Data.Generated";
        public const string Marker = "// <auto-generated by ThreeSouls Sheet Importer>";

        public sealed class Column
        {
            public string Name;
            public string TypeName;
            public string Description;
            public Type Type;
            public EnumDefinition GeneratedEnum;
        }

        public sealed class EnumDefinition
        {
            public string Name;
            public readonly Dictionary<string, int> Members = new Dictionary<string, int>(StringComparer.Ordinal);

            public int Add(string member)
            {
                ValidateName(member);
                if (member == Name) throw new FormatException("enum과 멤버 이름은 달라야 합니다: " + Name);
                if (!Members.TryGetValue(member, out int value))
                {
                    value = Members.Count == 0 ? 0 : checked(Members.Values.Max() + 1);
                    Members.Add(member, value);
                }
                return value;
            }
        }

        public static string GenerateEnumCode(EnumDefinition definition)
        {
            ValidateName(definition.Name);
            var code = new StringBuilder();
            code.AppendLine(Marker);
            code.AppendLine("namespace " + GeneratedNamespace);
            code.AppendLine("{");
            code.AppendLine("    public enum @" + definition.Name);
            code.AppendLine("    {");
            foreach (var member in definition.Members.OrderBy(m => m.Value))
                code.AppendLine("        @" + member.Key + " = " + member.Value.ToString(CultureInfo.InvariantCulture) + ",");
            code.AppendLine("    }");
            code.AppendLine("}");
            return code.ToString();
        }

        // 생성한 소스 자체를 번호 목록으로 사용합니다. 컴파일 전 재실행도 동일하게 처리합니다.
        public static EnumDefinition ReadEnumCode(string source)
        {
            var match = Regex.Match(source, @"public enum @([A-Za-z_][A-Za-z0-9_]*)");
            if (!match.Success) throw new FormatException("생성 enum 파일 형식이 아닙니다.");
            var definition = new EnumDefinition { Name = match.Groups[1].Value };
            foreach (Match member in Regex.Matches(source, @"@([A-Za-z_][A-Za-z0-9_]*) = ([0-9]+),"))
                definition.Members.Add(member.Groups[1].Value, int.Parse(member.Groups[2].Value, CultureInfo.InvariantCulture));
            if (source.Replace("\r\n", "\n") != GenerateEnumCode(definition).Replace("\r\n", "\n"))
                throw new FormatException("생성 enum 파일을 수동 수정했거나 형식이 다릅니다. 덮어쓰지 않습니다.");
            return definition;
        }

        public sealed class Table
        {
            public string Name;
            public Column[] Columns;
            public readonly List<object[]> Rows = new List<object[]>();
        }

        public static void ValidateName(string name)
        {
            if (string.IsNullOrEmpty(name) || !Regex.IsMatch(name, @"\A[A-Za-z_][A-Za-z0-9_]*\z"))
                throw new FormatException("이름은 영문/숫자/_만 사용하며 숫자로 시작할 수 없습니다: " + name);
        }

        // 쉼표, 셀 내부 개행, "" 이스케이프, UTF-8 BOM, CRLF/LF를 처리합니다.
        public static List<string[]> ParseCsv(string csv)
        {
            if (csv == null) throw new ArgumentNullException(nameof(csv));
            csv = csv.TrimStart('\uFEFF');
            var result = new List<string[]>();
            var row = new List<string>();
            var cell = new StringBuilder();
            bool quoted = false, closed = false, started = false;
            for (int i = 0; i < csv.Length; i++)
            {
                char c = csv[i];
                if (quoted)
                {
                    if (c != '"') { cell.Append(c); continue; }
                    if (i + 1 < csv.Length && csv[i + 1] == '"') { cell.Append('"'); i++; }
                    else { quoted = false; closed = true; }
                    continue;
                }
                if (c == ',' || c == '\r' || c == '\n')
                {
                    row.Add(cell.ToString());
                    cell.Clear(); closed = false; started = false;
                    if (c != ',')
                    {
                        result.Add(row.ToArray()); row.Clear();
                        if (c == '\r' && i + 1 < csv.Length && csv[i + 1] == '\n') i++;
                    }
                    continue;
                }
                if (closed) throw new FormatException("CSV: 닫는 따옴표 뒤에 잘못된 문자가 있습니다.");
                if (c == '"')
                {
                    if (started) throw new FormatException("CSV: 셀 중간의 따옴표는 따옴표로 감싼 셀 안에서 \"\"로 작성하세요.");
                    quoted = true; started = true;
                }
                else { cell.Append(c); started = true; }
            }
            if (quoted) throw new FormatException("CSV: 닫히지 않은 따옴표가 있습니다.");
            if (started || closed || row.Count > 0) { row.Add(cell.ToString()); result.Add(row.ToArray()); }
            return result;
        }

        public static Type ResolveType(string name)
        {
            bool array = name.EndsWith("[]", StringComparison.Ordinal);
            string element = array ? name.Substring(0, name.Length - 2) : name;
            Type type;
            switch (element)
            {
                case "int": type = typeof(int); break;
                case "long": type = typeof(long); break;
                case "float": type = typeof(float); break;
                case "double": type = typeof(double); break;
                case "bool": type = typeof(bool); break;
                case "string": type = typeof(string); break;
                case "Vector2":
                case "UnityEngine.Vector2":
                    type = ResolveVector2Type();
                    break;
                default:
                    var match = Regex.Match(element, @"\AEnum<\s*([A-Za-z_][A-Za-z0-9_.]*)\s*>\z");
                    if (!match.Success) throw new FormatException("지원하지 않는 타입: " + name);
                    type = ResolveEnum(match.Groups[1].Value);
                    break;
            }
            return array ? type.MakeArrayType() : type;
        }

        /// <summary>
        /// Unity를 직접 참조하지 않고 로드된 어셈블리에서 Vector2 타입을 조회합니다.
        /// </summary>
        private static Type ResolveVector2Type()
        {
            var assemblies = AppDomain.CurrentDomain.GetAssemblies();

            for (int i = 0; i < assemblies.Length; i++)
            {
                var type = assemblies[i].GetType("UnityEngine.Vector2", false);

                if (type != null)
                {
                    return type;
                }
            }

            throw new FormatException("Vector2 타입을 찾을 수 없습니다. Unity 에디터에서 시트를 가져오세요.");
        }

        private static Type ResolveEnum(string name, bool allowMissing = false)
        {
            var matches = new List<Type>();
            foreach (Assembly assembly in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type[] types;
                try {
                    types = assembly.GetTypes(); 
                }
                catch (ReflectionTypeLoadException e)
                { 
                    types = e.Types;
                }
                foreach (Type type in types)
                {
                    if (type != null && type.IsEnum && type.IsVisible && !type.ContainsGenericParameters &&
                        (type.Name == name || type.FullName.Replace('+', '.') == name)) matches.Add(type);
                }
            }
            if (matches.Count == 0 && allowMissing)
            {
                return null;
            }

            if (matches.Count == 0)
            { 
                throw new FormatException("enum을 찾을 수 없습니다: " + name + ". 먼저 런타임 C#에 enum을 선언하고 컴파일하세요.");
            }

            if (matches.Count > 1)
            {
                throw new FormatException("enum 이름이 중복됩니다. Enum<전체.namespace.타입명>으로 지정하세요: " +
                    string.Join(", ", matches.Select(t => t.FullName.Replace('+', '.'))));
            }

            Type result = matches[0];

            if (!result.IsVisible || result.ContainsGenericParameters)
            {
                throw new FormatException("외부에서 접근 가능한 public enum이어야 합니다: " + name);
            }

            string assemblyName = result.Assembly.GetName().Name;
            // Unity가 생성하는 런타임 Assembly-CSharp도 Editor에서 컴파일될 때 UnityEditor를
            // 참조할 수 있으므로 참조 목록만으로 Editor 전용 어셈블리라고 판단하지 않습니다.
            if (assemblyName.EndsWith("-Editor", StringComparison.Ordinal) ||
                assemblyName.EndsWith(".Editor", StringComparison.Ordinal))
            { 
                throw new FormatException("Editor 전용 enum은 런타임 데이터에 사용할 수 없습니다: " + name);
            }

            Type underlying = Enum.GetUnderlyingType(result);

            if (underlying == typeof(long) || underlying == typeof(ulong))
            { 
                throw new FormatException("Unity 직렬화를 위해 32비트 이하 기반 enum을 사용하세요: " + name); 
            }
            return result;
        }

        private static string CodeTypeName(Column column)
        {
            if (column.GeneratedEnum != null)
                return "global::" + string.Join(".", (GeneratedNamespace + "." + column.GeneratedEnum.Name).Split('.').Select(p => "@" + p)) +
                    (column.TypeName.EndsWith("[]", StringComparison.Ordinal) ? "[]" : "");
            Type type = column.Type.IsArray ? column.Type.GetElementType() : column.Type;
            if (type.FullName == "UnityEngine.Vector2")
            {
                return "global::UnityEngine.Vector2" + (column.Type.IsArray == true ? "[]" : "");
            }

            if (!type.IsEnum) return column.TypeName;
            // namespace 충돌과 C# 예약어를 피하고 중첩 enum도 올바르게 생성합니다.
            return "global::" + string.Join(".", type.FullName.Replace('+', '.').Split('.').Select(p => "@" + p)) +
                (column.Type.IsArray ? "[]" : "");
        }

        public static object ConvertCell(string value, Type type)
        {
            if (type == typeof(string)) return value;
            if (type.IsArray)
            {
                Type element = type.GetElementType();
                string[] parts = ParseArrayCell(value, element.FullName == "UnityEngine.Vector2");
                Array array = Array.CreateInstance(element, parts.Length);
                for (int i = 0; i < parts.Length; i++) array.SetValue(ConvertCell(parts[i], element), i);
                return array;
            }
            value = value.Trim();
            if (value.Length == 0) throw new FormatException("숫자/bool/enum/Vector2 셀은 비워 둘 수 없습니다.");
            if (type.FullName == "UnityEngine.Vector2")
            {
                return ConvertVector2Cell(value, type);
            }

            if (type.IsEnum)
            {
                try
                {
                    // 이름은 대소문자를 구분합니다. 숫자도 선언된 값만 허용합니다.
                    if (value.Contains(",")) throw new ArgumentException();
                    object parsed = Enum.Parse(type, value, false);
                    if (Enum.IsDefined(type, parsed)) return parsed;
                }
                catch (Exception e) when (e is ArgumentException || e is OverflowException) { }
                throw new FormatException(type.FullName + "에 선언된 enum 이름 또는 숫자를 입력하세요: " + value);
            }
            var culture = CultureInfo.InvariantCulture;
            if (type == typeof(int)) return int.Parse(value, NumberStyles.Integer, culture);
            if (type == typeof(long)) return long.Parse(value, NumberStyles.Integer, culture);
            if (type == typeof(float))
            {
                float number = float.Parse(value, NumberStyles.Float, culture);
                if (float.IsNaN(number) || float.IsInfinity(number)) throw new FormatException("유한한 float 값이 필요합니다.");
                return number;
            }
            if (type == typeof(double))
            {
                double number = double.Parse(value, NumberStyles.Float, culture);
                if (double.IsNaN(number) || double.IsInfinity(number)) throw new FormatException("유한한 double 값이 필요합니다.");
                return number;
            }
            if (type == typeof(bool))
            {
                if (value == "1") return true;
                if (value == "0") return false;
                return bool.Parse(value);
            }
            throw new FormatException("지원하지 않는 타입: " + type);
        }

        /// <summary>
        /// x,y 또는 괄호로 감싼 두 좌표를 유한한 float 값으로 변환합니다.
        /// 소수점과 지수 표기는 기존 숫자 셀과 같은 고정 문화권 규칙을 사용합니다.
        /// </summary>
        private static object ConvertVector2Cell(string value, Type type)
        {
            if (value.StartsWith("(", StringComparison.Ordinal) == true ||
                value.StartsWith("[", StringComparison.Ordinal) == true)
            {
                var closing = value[0] == '(' ? ")" : "]";

                if (value.EndsWith(closing, StringComparison.Ordinal) == false)
                {
                    throw new FormatException("Vector2 좌표의 괄호를 올바르게 닫아주세요: " + value);
                }

                value = value.Substring(1, value.Length - 2);
            }

            var parts = value.Split(',');

            if (parts.Length != 2)
            {
                throw new FormatException("Vector2는 x,y 형식의 두 좌표가 필요합니다. 예: 0,0.5 또는 (0,0.5)");
            }

            var x = (float)ConvertCell(parts[0], typeof(float));
            var y = (float)ConvertCell(parts[1], typeof(float));
            return Activator.CreateInstance(type, x, y);
        }

        /// <summary>
        /// 대괄호 배열 또는 파이프로 구분한 배열을 읽고 빈 배열 및 원소 형식을 검증합니다.
        /// Vector2 배열은 좌표 내부의 구분자를 보존합니다.
        /// </summary>
        private static string[] ParseArrayCell(string value, bool vectorElements = false)
        {
            if (string.IsNullOrWhiteSpace(value)) return new string[0];

            value = value.Trim();
            bool startsWithBracket = value.StartsWith("[", StringComparison.Ordinal);
            bool endsWithBracket = value.EndsWith("]", StringComparison.Ordinal);
            if (startsWithBracket != endsWithBracket)
                throw new FormatException("배열의 대괄호를 올바르게 닫아주세요: " + value);

            string content = startsWithBracket ? value.Substring(1, value.Length - 2).Trim() : value;
            if (content.Length == 0) return new string[0];

            char separator = startsWithBracket ? ',' : '|';
            string[] parts = vectorElements == true ? SplitVectorArray(content, separator) : content.Split(separator);
            for (int i = 0; i < parts.Length; i++)
            {
                parts[i] = parts[i].Trim();
                if (parts[i].Length == 0)
                    throw new FormatException("배열에 빈 값을 사용할 수 없습니다: " + value);
            }
            return parts;
        }

        /// <summary>
        /// Vector2 내부 좌표의 쉼표를 유지하고 괄호 밖의 구분자로만 배열 원소를 나눕니다.
        /// 기존 단순 타입 배열의 파싱 형식에는 영향을 주지 않습니다.
        /// </summary>
        private static string[] SplitVectorArray(string content, char separator)
        {
            var parts = new List<string>();
            var brackets = new Stack<char>();
            var start = 0;

            for (int i = 0; i < content.Length; i++)
            {
                var character = content[i];

                if (character == '(' || character == '[')
                {
                    brackets.Push(character);
                }
                else if (character == ')' || character == ']')
                {
                    if (brackets.Count == 0 || brackets.Pop() != (character == ')' ? '(' : '['))
                    {
                        throw new FormatException("Vector2 배열의 괄호를 올바르게 닫아주세요: " + content);
                    }
                }
                else if (character == separator && brackets.Count == 0)
                {
                    parts.Add(content.Substring(start, i - start));
                    start = i + 1;
                }
            }

            if (brackets.Count != 0)
            {
                throw new FormatException("Vector2 배열의 괄호를 올바르게 닫아주세요: " + content);
            }

            parts.Add(content.Substring(start));
            return parts.ToArray();
        }

        public static Table Read(string name, string csv, string uniqueKey = "", Dictionary<string, EnumDefinition> generatedEnums = null)
        {
            ValidateName(name);
            List<string[]> records = ParseCsv(csv);
            if (records.Count < 2) throw new FormatException("첫 행 스키마와 둘째 행 설명이 필요합니다.");
            int width = records[0].Length;
            while (width > 0 && string.IsNullOrWhiteSpace(records[0][width - 1])) width--;
            if (width == 0) throw new FormatException("첫 행에 변수명 : 타입을 입력하세요.");
            var table = new Table { Name = name, Columns = new Column[width] };
            var names = new HashSet<string>(StringComparer.Ordinal);
            for (int col = 0; col < width; col++)
            {
                string header = records[0][col];
                int colon = header.IndexOf(':');
                if (colon < 1 || colon != header.LastIndexOf(':'))
                    throw new FormatException("1행 " + (col + 1) + "열: 변수명 : 타입 형식이 필요합니다.");
                string field = header.Substring(0, colon).Trim();
                string typeName = header.Substring(colon + 1).Trim();
                ValidateName(field);
                if (!names.Add(field) || field == name + "Row")
                    throw new FormatException("중복되었거나 행 클래스명과 같은 변수명: " + field);
                var column = new Column
                {
                    Name = field, TypeName = typeName,
                    Description = col < records[1].Length ? records[1][col] : ""
                };
                // 1번 단계에서는 아직 컴파일되지 않은 enum을 스키마 정보로 보관합니다.
                var enumMatch = Regex.Match(typeName, @"\AEnum<\s*([A-Za-z_][A-Za-z0-9_]*)\s*>(\[\])?\z");
                if (generatedEnums != null && enumMatch.Success)
                {
                    string enumName = enumMatch.Groups[1].Value;
                    if (!generatedEnums.TryGetValue(enumName, out var definition) && ResolveEnum(enumName, true) == null)
                    {
                        definition = new EnumDefinition { Name = enumName };
                        generatedEnums.Add(enumName, definition);
                    }
                    column.GeneratedEnum = definition;
                }
                if (column.GeneratedEnum == null) column.Type = ResolveType(typeName);
                table.Columns[col] = column;
            }
            // 헤더 없이 설명/데이터만 들어 있는 열도 조용히 버리지 않습니다.
            for (int row = 1; row < records.Count; row++)
                for (int col = width; col < records[row].Length; col++)
                    if (!string.IsNullOrWhiteSpace(records[row][col]))
                        throw new FormatException((row + 1) + "행 " + (col + 1) + "열: 헤더가 없습니다.");
            int keyIndex = -1;
            if (!string.IsNullOrWhiteSpace(uniqueKey))
            {
                keyIndex = Array.FindIndex(table.Columns, c => c.Name == uniqueKey);
                if (keyIndex < 0) throw new FormatException("고유 키 열이 없습니다: " + uniqueKey);
                Type keyType = table.Columns[keyIndex].Type;
                if (keyType != typeof(string) && keyType != typeof(int) && keyType != typeof(long))
                    throw new FormatException("고유 키 타입은 string/int/long이어야 합니다.");
            }
            var keys = new HashSet<object>();
            for (int row = 2; row < records.Count; row++)
            {
                string[] cells = records[row];
                if (cells.All(string.IsNullOrWhiteSpace)) continue;
                var values = new object[width];
                for (int col = 0; col < width; col++)
                {
                    try
                    {
                        string cell = col < cells.Length ? cells[col] : "";
                        Column column = table.Columns[col];
                        if (column.GeneratedEnum == null) values[col] = ConvertCell(cell, column.Type);
                        else if (column.TypeName.EndsWith("[]", StringComparison.Ordinal))
                            values[col] = ParseArrayCell(cell).Select(v => column.GeneratedEnum.Add(v)).ToArray();
                        else values[col] = column.GeneratedEnum.Add(cell.Trim());
                    }
                    catch (Exception e) when (e is FormatException || e is OverflowException)
                    {
                        throw new FormatException(name + ": " + (row + 1) + "행 " + (col + 1) + "열 (" + table.Columns[col].Name + "): " + e.Message, e);
                    }
                }
                if (keyIndex >= 0)
                {
                    object key = values[keyIndex];
                    if ((key is string s && string.IsNullOrWhiteSpace(s)) || !keys.Add(key))
                        throw new FormatException(name + ": " + (row + 1) + "행의 고유 키가 비었거나 중복입니다: " + key);
                }
                table.Rows.Add(values);
            }
            return table;
        }

        private static string Literal(string value)
        {
            var output = new StringBuilder("\"");
            foreach (char c in value)
            {
                // 제어 문자/개행/따옴표뿐 아니라 유니코드도 안전하게 코드에 기록합니다.
                if (c < 32 || c > 126 || c == '"' || c == '\\') output.Append("\\u" + ((int)c).ToString("x4"));
                else output.Append(c);
            }
            return output.Append('"').ToString();
        }

        public static string GenerateCode(Table table)
        {
            ValidateName(table.Name);
            string rowName = table.Name + "Row";
            var code = new StringBuilder();
            code.AppendLine(Marker);
            code.AppendLine("// 변경은 원본 시트에 반영한 뒤 다시 생성하세요.");
            code.AppendLine("namespace " + GeneratedNamespace);
            code.AppendLine("{");
            code.AppendLine("    [global::System.Serializable]");
            code.AppendLine("    public sealed class " + rowName);
            code.AppendLine("    {");
            foreach (Column column in table.Columns)
            {
                string xml = column.Description.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")
                    .Replace("\r", " ").Replace("\n", " ").Replace("\u0085", " ").Replace("\u2028", " ").Replace("\u2029", " ");
                code.AppendLine("        /// <summary>" + xml + "</summary>");
                code.AppendLine("        [global::UnityEngine.Tooltip(" + Literal(column.Description) + ")]");
                code.AppendLine("        public " + CodeTypeName(column) + " @" + column.Name + ";");
            }
            code.AppendLine("    }");
            code.AppendLine("    [global::System.Serializable]");
            code.AppendLine("    public sealed class " + table.Name + "Payload");
            code.AppendLine("    {");
            code.AppendLine("        public " + rowName + "[] Items = new " + rowName + "[0];");
            code.AppendLine("    }");
            code.AppendLine("    [global::UnityEngine.CreateAssetMenu(menuName = \"Three Souls/Tables/" + table.Name + "\")]");
            code.AppendLine("    public sealed class " + table.Name + "Table : global::UnityEngine.ScriptableObject");
            code.AppendLine("    {");
            code.AppendLine("        public " + rowName + "[] Items = new " + rowName + "[0];");
            code.AppendLine("    }");
            code.AppendLine("}");
            return code.ToString();
        }
    }
